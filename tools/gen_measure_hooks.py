#!/usr/bin/env python3
"""Generate src/measure_hooks.inc: timing wrappers for X-Plane's Vulkan device calls.

Used only with measure_driver=1 in the INI (off by default). Each wrapper reads the CPU time stamp counter around
the call into the next layer / driver and adds it to one category. Re-run after changing Vulkan-Headers:
    python3 tools/gen_measure_hooks.py Vulkan-Headers/include/vulkan/vulkan_core.h > src/measure_hooks.inc
"""
import re
import sys

# device-level functions (besides vkCmd*) worth timing, with their category
EXTRA = {
    "vkBeginCommandBuffer": "CB", "vkEndCommandBuffer": "CB", "vkResetCommandBuffer": "CB",
    "vkResetCommandPool": "CB", "vkAllocateCommandBuffers": "CB", "vkFreeCommandBuffers": "CB",
    "vkUpdateDescriptorSets": "DESC", "vkUpdateDescriptorSetWithTemplate": "DESC",
    "vkUpdateDescriptorSetWithTemplateKHR": "DESC", "vkAllocateDescriptorSets": "DESC",
    "vkFreeDescriptorSets": "DESC", "vkResetDescriptorPool": "DESC",
    "vkWaitForFences": "WAIT", "vkGetFenceStatus": "WAIT", "vkWaitSemaphores": "WAIT",
    "vkWaitSemaphoresKHR": "WAIT", "vkGetQueryPoolResults": "WAIT", "vkGetSemaphoreCounterValue": "WAIT",
    "vkGetSemaphoreCounterValueKHR": "WAIT", "vkResetFences": "WAIT",
    "vkMapMemory": "MAP", "vkUnmapMemory": "MAP", "vkMapMemory2": "MAP", "vkMapMemory2KHR": "MAP",
    "vkUnmapMemory2": "MAP", "vkUnmapMemory2KHR": "MAP",
    "vkFlushMappedMemoryRanges": "MAP", "vkInvalidateMappedMemoryRanges": "MAP",
    "vkCreateGraphicsPipelines": "PIPE", "vkCreateComputePipelines": "PIPE",
    "vkCreateShaderModule": "PIPE", "vkCreateBuffer": "RES", "vkDestroyBuffer": "RES", "vkCreateImage": "RES",
    "vkDestroyImage": "RES", "vkCreateImageView": "RES", "vkDestroyImageView": "RES",
    "vkAllocateMemory": "RES", "vkFreeMemory": "RES", "vkBindBufferMemory": "RES", "vkBindImageMemory": "RES",
    "vkBindBufferMemory2": "RES", "vkBindImageMemory2": "RES",
    "vkCreateFramebuffer": "RES", "vkDestroyFramebuffer": "RES",
}


def category(name):
    if name in EXTRA:
        return EXTRA[name]
    if name.startswith("vkCmdDraw"):
        return "DRAW"
    if name.startswith("vkCmdDispatch") or name.startswith("vkCmdTraceRays"):
        return "DISPATCH"
    if name.startswith("vkCmdBind") or name.startswith("vkCmdPushDescriptor") or name.startswith("vkCmdPushConstants") \
            or name.startswith("vkCmdSetDescriptor"):
        return "BIND"
    if re.match(r"vkCmd(Begin|End|Next)(RenderPass|Rendering|Subpass)", name) or name.startswith("vkCmdNextSubpass"):
        return "PASS"
    if re.match(r"vkCmd(PipelineBarrier|Copy|Blit|Clear|Update|Fill|Resolve|WaitEvents|SetEvent|ResetEvent)", name):
        return "COPY"
    return "CMD"


def main(path):
    text = open(path, encoding="utf-8").read()
    protos = re.findall(r"VKAPI_ATTR\s+(\w+)\s+VKAPI_CALL\s+(vk\w+)\(\s*(.*?)\);", text, re.S)
    seen, out = set(), []
    for ret, name, params in protos:
        if name in seen:
            continue
        if not (name.startswith("vkCmd") or name in EXTRA):
            continue
        seen.add(name)
        plist = [" ".join(p.split()) for p in params.split(",")]
        args = []
        for p in plist:
            m = re.search(r"(\w+)\s*(\[[^\]]*\])?$", p)
            args.append(m.group(1))
        cat = category(name)
        decl = ", ".join(plist)
        call = "m_%s(%s)" % (name, ", ".join(args))
        out.append("static PFN_%s m_%s = nullptr;" % (name, name))
        if ret == "void":
            body = "uint64_t t0 = __rdtsc(); %s; mAdd(M_%s, __rdtsc() - t0);" % (call, cat)
        else:
            body = "uint64_t t0 = __rdtsc(); %s r = %s; mAdd(M_%s, __rdtsc() - t0); return r;" % (ret, call, cat)
        out.append("static VKAPI_ATTR %s VKAPI_CALL w_%s(%s) { %s }" % (ret, name, decl, body))
    print("// Generated by tools/gen_measure_hooks.py from %s - do not edit." % path.split("/")[-1])
    print("// %d timed device functions." % len(seen))
    print("\n".join(out))
    print("static const MeasureHook kMeasureHooks[] = {")
    for name in sorted(seen):
        print('    {"%s", (PFN_vkVoidFunction)w_%s, (PFN_vkVoidFunction*)&m_%s},' % (name, name, name))
    print("};")


if __name__ == "__main__":
    main(sys.argv[1])
